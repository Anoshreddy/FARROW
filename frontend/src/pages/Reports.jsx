import { useMemo, useState } from 'react';
import { useSearchParams } from 'react-router-dom';
import { Archive, ArrowLeftRight, BellRing, Boxes, CalendarClock, ClipboardList, Flame, Trash2, Warehouse } from 'lucide-react';
import AppShell from '../components/AppShell';
import KpiCard from '../components/KpiCard';
import Section from '../components/Section';
import DataTable from '../components/DataTable';
import StatusBadge, { SeverityBadge } from '../components/StatusBadge';
import { BarChart } from '../components/Charts';
import { DateFilter, FilterBar, SelectFilter } from '../components/FilterBar';
import { ErrorState, LoadingState } from '../components/AsyncState';
import { useApi } from '../api/useApi';
import { useRefData } from '../api/useRefData';
import { api } from '../api/client';
import { SEVERITY_ORDER, TYPE_LABELS } from '../lib/alerts';
import { daysLabel, expiryBucket } from '../lib/expiry';
import { formatDate, formatNumber, todayISO } from '../lib/format';

const REPORTS = [
  { id: 'inventory-summary', title: 'Inventory Summary', icon: ClipboardList, desc: 'Headline counts for stock, expiry and reorders.' },
  { id: 'inventory', title: 'Inventory', icon: Boxes, desc: 'Current stock per material and warehouse.' },
  { id: 'expiry', title: 'Expiry', icon: CalendarClock, desc: 'Batches with stock, by expiry status.' },
  { id: 'consumption', title: 'Consumption', icon: Flame, desc: 'Total consumed per material and warehouse.' },
  { id: 'wastage', title: 'Wastage', icon: Trash2, desc: 'Total written off per material and warehouse.' },
  { id: 'stock-movements', title: 'Stock Movements', icon: ArrowLeftRight, desc: 'Totals by movement type.' },
  { id: 'warehouse-summary', title: 'Warehouse Summary', icon: Warehouse, desc: 'What each warehouse currently holds.' },
  { id: 'alerts', title: 'Alerts', icon: BellRing, desc: 'Active expiry, risk and reorder alerts.' },
];
const FILTERED = ['consumption', 'wastage', 'stock-movements'];

export default function Reports() {
  const [sp, setSp] = useSearchParams();
  const ref = useRefData();
  const active = REPORTS.find((r) => r.id === sp.get('report')) || REPORTS[0];
  const [filters, setFilters] = useState({ material: '', warehouse: '', from: '', to: '' });
  const [tick, setTick] = useState(0);
  const setF = (k) => (v) => setFilters((f) => ({ ...f, [k]: v }));

  // Query params understood by the consumption / wastage / stock-movements endpoints.
  const params = {
    raw_material_id: filters.material,
    warehouse_id: filters.warehouse,
    start_date: filters.from,
    end_date: filters.to ? `${filters.to}T23:59:59` : '',
  };
  const hasFilters = Object.values(filters).some(Boolean);
  const key = `${active.id}-${tick}-${JSON.stringify(params)}`;

  return (
    <AppShell
      title="Reports"
      description="Pick a report to see the figures generated by the FARROW backend."
      onRefresh={() => {
        setTick((t) => t + 1);
        ref.reload();
      }}
    >
      <div className="report-grid" role="tablist" aria-label="Reports">
        {REPORTS.map((r) => (
          <button key={r.id} role="tab" aria-selected={active.id === r.id} className={`report-card ${active.id === r.id ? 'is-active' : ''}`} onClick={() => setSp({ report: r.id }, { replace: true })}>
            <span className="report-card-icon"><r.icon size={15} /></span>
            <span>
              <span className="report-card-title">{r.title}</span>
              <span className="report-card-desc">{r.desc}</span>
            </span>
          </button>
        ))}
      </div>

      {FILTERED.includes(active.id) && ref.status === 'success' && (
        <FilterBar canReset={hasFilters} onReset={() => setFilters({ material: '', warehouse: '', from: '', to: '' })}>
          <SelectFilter label="Raw material" value={filters.material} onChange={setF('material')} options={ref.materials.map((m) => ({ value: String(m.id), label: m.name }))} allLabel="All materials" />
          <SelectFilter label="Warehouse" value={filters.warehouse} onChange={setF('warehouse')} options={ref.warehouses.map((w) => ({ value: String(w.id), label: w.name }))} allLabel="All warehouses" />
          <DateFilter label="From" value={filters.from} onChange={setF('from')} max={filters.to || undefined} />
          <DateFilter label="To" value={filters.to} onChange={setF('to')} min={filters.from || undefined} />
        </FilterBar>
      )}

      {active.id === 'inventory-summary' && <SummaryReport key={key} />}
      {active.id === 'inventory' && <InventoryReport key={key} />}
      {active.id === 'expiry' && <ExpiryReport key={key} />}
      {active.id === 'consumption' && (
        <QuantityReport key={key} title="Consumption" subtitle="Total CONSUME movements per material and warehouse." fetcher={() => api.getConsumptionReport(params)} valueKey="total_consumed_quantity" countKey="consumption_count" valueHeader="Total Consumed" empty="No consumption has been recorded for these filters." icon={Flame} />
      )}
      {active.id === 'wastage' && (
        <QuantityReport key={key} title="Wastage" subtitle="Total WASTAGE movements per material and warehouse." fetcher={() => api.getWastageReport(params)} valueKey="total_wastage_quantity" countKey="wastage_count" valueHeader="Total Wasted" empty="No wastage has been recorded for these filters." icon={Trash2} />
      )}
      {active.id === 'stock-movements' && <MovementsReport key={key} params={params} />}
      {active.id === 'warehouse-summary' && <WarehouseReport key={key} />}
      {active.id === 'alerts' && <AlertsReport key={key} />}
    </AppShell>
  );
}

function SummaryReport() {
  const state = useApi(() => api.getInventorySummary({ prediction_date: todayISO() }), []);
  const d = state.data;
  return (
    <Section title="Inventory Summary" subtitle="Headline figures. Reorder and risk counts are per material/warehouse pair.">
      {state.status === 'loading' && <LoadingState label="Evaluating summary…" />}
      {state.status === 'error' && <ErrorState message={state.error.message} onRetry={state.reload} />}
      {d && (
        <div className="kpi-row" style={{ marginBottom: 0 }}>
          <KpiCard label="Raw materials" value={d.total_raw_materials} />
          <KpiCard label="Warehouses" value={d.total_warehouses} />
          <KpiCard label="Total stock quantity" value={formatNumber(d.total_inventory_quantity)} hint="All units combined" />
          <KpiCard label="Active batches" value={d.active_inventory_batches} />
          <KpiCard label="High stockout risk" value={d.high_risk_materials} tone={d.high_risk_materials > 0 ? 'critical' : 'default'} hint="Material/warehouse pairs" />
          <KpiCard label="Needing reorder" value={d.materials_requiring_reorder} tone={d.materials_requiring_reorder > 0 ? 'warning' : 'default'} hint="Material/warehouse pairs" />
          <KpiCard label="Expiring soon" value={d.batches_expiring_soon} tone={d.batches_expiring_soon > 0 ? 'warning' : 'default'} hint="Within 30 days" />
          <KpiCard label="Expired batches" value={d.expired_batches} tone={d.expired_batches > 0 ? 'critical' : 'default'} />
        </div>
      )}
    </Section>
  );
}

function InventoryReport() {
  const state = useApi(() => api.getInventoryReport(), []);
  const cols = [
    { key: 'raw_material_name', header: 'Raw Material', sortValue: (r) => r.raw_material_name, render: (r) => <strong>{r.raw_material_name}</strong> },
    { key: 'warehouse_name', header: 'Warehouse', sortValue: (r) => r.warehouse_name },
    { key: 'current_stock', header: 'Current Stock', align: 'right', sortValue: (r) => r.current_stock, render: (r) => `${formatNumber(r.current_stock)} ${r.unit}` },
    { key: 'number_of_batches', header: 'Batches', align: 'right', sortValue: (r) => r.number_of_batches },
  ];
  return (
    <Section title="Inventory" subtitle="Only combinations that currently hold batches are listed.">
      <DataTable columns={cols} rows={state.data || []} rowKey={(r) => `${r.raw_material_id}-${r.warehouse_id}`} loading={state.status === 'loading'} error={state.error} onRetry={state.reload} emptyIcon={Archive} emptyTitle="No inventory" emptyMessage="No inventory has been recorded yet." />
    </Section>
  );
}

function ExpiryReport() {
  const state = useApi(() => api.getExpiryReport(), []);
  const rows = (state.data || []).map((r) => ({ ...r, bucket: expiryBucket(r) }));
  const count = (...b) => rows.filter((r) => b.includes(r.bucket)).length;
  const cols = [
    { key: 'batch_number', header: 'Batch', sortValue: (r) => r.batch_number, render: (r) => <strong>{r.batch_number}</strong> },
    { key: 'raw_material_name', header: 'Raw Material', sortValue: (r) => r.raw_material_name },
    { key: 'warehouse_name', header: 'Warehouse', sortValue: (r) => r.warehouse_name },
    { key: 'quantity', header: 'Quantity', align: 'right', sortValue: (r) => r.quantity, render: (r) => formatNumber(r.quantity) },
    { key: 'expiry_date', header: 'Expiry Date', sortValue: (r) => r.expiry_date, render: (r) => (r.expiry_date ? formatDate(r.expiry_date) : '—') },
    { key: 'days_until_expiry', header: 'Days Remaining', align: 'right', sortValue: (r) => r.days_until_expiry, render: (r) => daysLabel(r.days_until_expiry) },
    { key: 'bucket', header: 'Status', render: (r) => <StatusBadge status={r.bucket} /> },
  ];
  return (
    <Section title="Expiry" subtitle="Batches with stock on hand, by expiry status.">
      {state.status === 'success' && (
        <div className="kpi-row kpi-row--4">
          <KpiCard label="Expired" value={count('EXPIRED')} tone={count('EXPIRED') > 0 ? 'critical' : 'default'} />
          <KpiCard label="Within 7 days" value={count('DUE_7')} tone={count('DUE_7') > 0 ? 'warning' : 'default'} />
          <KpiCard label="Within 30 days" value={count('DUE_7', 'DUE_30')} tone={count('DUE_7', 'DUE_30') > 0 ? 'warning' : 'default'} hint="Includes the 7-day batches" />
          <KpiCard label="Safe" value={count('SAFE')} tone="healthy" />
        </div>
      )}
      <DataTable columns={cols} rows={rows} rowKey={(r) => r.batch_id} loading={state.status === 'loading'} error={state.error} onRetry={state.reload} initialSort={{ key: 'days_until_expiry', dir: 'asc' }} rowTone={(r) => (r.bucket === 'EXPIRED' ? 'critical' : r.bucket === 'DUE_7' || r.bucket === 'DUE_30' ? 'warning' : null)} emptyIcon={CalendarClock} emptyTitle="No batches with stock" emptyMessage="Batches appear here once stock has been received." />
    </Section>
  );
}

// Bars are only drawn per unit, so kg is never compared against L.
function QuantityReport({ title, subtitle, fetcher, valueKey, countKey, valueHeader, empty, icon }) {
  const state = useApi(fetcher, []);
  const rows = state.data || [];
  const groups = useMemo(() => {
    const g = {};
    rows.forEach((r) => (g[r.unit] = [...(g[r.unit] || []), r]));
    return Object.entries(g);
  }, [rows]);
  const cols = [
    { key: 'raw_material_name', header: 'Raw Material', sortValue: (r) => r.raw_material_name, render: (r) => <strong>{r.raw_material_name}</strong> },
    { key: 'warehouse_name', header: 'Warehouse', sortValue: (r) => r.warehouse_name },
    { key: valueKey, header: valueHeader, align: 'right', sortValue: (r) => r[valueKey], render: (r) => `${formatNumber(r[valueKey])} ${r.unit}` },
    { key: countKey, header: 'Movements', align: 'right', sortValue: (r) => r[countKey] },
  ];
  return (
    <Section title={title} subtitle={subtitle}>
      {state.status === 'success' && rows.length > 0 && (
        <div style={{ marginBottom: 22 }}>
          {groups.map(([unit, list]) => (
            <div key={unit} style={{ marginBottom: 16 }}>
              <p className="chart-caption">Quantity in {unit}</p>
              <BarChart data={list.map((r) => ({ label: `${r.raw_material_name} · ${r.warehouse_name}`, value: r[valueKey] }))} labelKey="label" valueKey="value" unit={unit} />
            </div>
          ))}
        </div>
      )}
      <DataTable columns={cols} rows={rows} rowKey={(r) => `${r.raw_material_name}-${r.warehouse_name}`} loading={state.status === 'loading'} error={state.error} onRetry={state.reload} emptyIcon={icon} emptyTitle="No data" emptyMessage={empty} />
    </Section>
  );
}

function MovementsReport({ params }) {
  const state = useApi(() => api.getStockMovementsReport(params), []);
  const rows = state.data || [];
  const cols = [
    { key: 'movement_type', header: 'Movement Type', render: (r) => <StatusBadge status={r.movement_type} /> },
    { key: 'count', header: 'Movements', align: 'right', sortValue: (r) => r.count },
    { key: 'total_quantity', header: 'Total Quantity', align: 'right', sortValue: (r) => r.total_quantity, render: (r) => formatNumber(r.total_quantity) },
  ];
  return (
    <Section title="Stock Movements" subtitle="Totals by movement type. Quantities add up different units of measure, so only the movement counts are charted.">
      {state.status === 'success' && rows.length > 0 && (
        <div style={{ marginBottom: 22 }}>
          <p className="chart-caption">Number of movements</p>
          <BarChart data={rows.map((r) => ({ label: (TYPE_LABELS[r.movement_type] || r.movement_type.replace('_', ' ')).toLowerCase(), value: r.count }))} labelKey="label" valueKey="value" />
        </div>
      )}
      <DataTable columns={cols} rows={rows} rowKey={(r) => r.movement_type} loading={state.status === 'loading'} error={state.error} onRetry={state.reload} emptyIcon={ArrowLeftRight} emptyTitle="No movements" emptyMessage="No stock movements for these filters." />
    </Section>
  );
}

function WarehouseReport() {
  const state = useApi(() => api.getWarehouseSummary(), []);
  const cols = [
    { key: 'warehouse_code', header: 'Code', sortValue: (r) => r.warehouse_code },
    { key: 'warehouse_name', header: 'Warehouse', sortValue: (r) => r.warehouse_name, render: (r) => <strong>{r.warehouse_name}</strong> },
    { key: 'location', header: 'Location' },
    { key: 'number_of_raw_materials', header: 'Materials', align: 'right', sortValue: (r) => r.number_of_raw_materials },
    { key: 'number_of_batches', header: 'Batches', align: 'right', sortValue: (r) => r.number_of_batches },
    { key: 'total_current_stock', header: 'Total Stock', align: 'right', sortValue: (r) => r.total_current_stock, render: (r) => formatNumber(r.total_current_stock) },
  ];
  return (
    <Section title="Warehouse Summary" subtitle="Total stock adds up every unit of measure, so it is shown as a table rather than a chart.">
      <DataTable columns={cols} rows={state.data || []} rowKey={(r) => r.warehouse_id} loading={state.status === 'loading'} error={state.error} onRetry={state.reload} emptyIcon={Warehouse} emptyTitle="No warehouses" emptyMessage="No warehouses found." />
    </Section>
  );
}

function AlertsReport() {
  const state = useApi(() => api.getAlerts({ prediction_date: todayISO() }), []);
  const rows = (state.data || []).map((a, i) => ({ ...a, id: i }));
  const cols = [
    { key: 'severity', header: 'Severity', sortValue: (r) => SEVERITY_ORDER[r.severity] ?? 9, render: (r) => <SeverityBadge severity={r.severity} /> },
    { key: 'type', header: 'Alert Type', sortValue: (r) => r.type, render: (r) => TYPE_LABELS[r.type] || r.type },
    { key: 'message', header: 'Description', render: (r) => <div className="cell-wrap">{r.message}</div> },
  ];
  return (
    <Section title="Alerts" subtitle={`Alerts generated as of ${formatDate(todayISO())}.`}>
      <DataTable columns={cols} rows={rows} rowKey={(r) => r.id} loading={state.status === 'loading'} error={state.error} onRetry={state.reload} initialSort={{ key: 'severity', dir: 'asc' }} rowTone={(r) => (r.severity === 'HIGH' ? 'critical' : r.severity === 'MEDIUM' ? 'warning' : null)} emptyIcon={BellRing} emptyTitle="No active alerts" emptyMessage="Everything currently looks clear." />
    </Section>
  );
}
